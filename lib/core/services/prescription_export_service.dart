import 'dart:io';
import 'dart:typed_data';

import 'package:flutter/foundation.dart';
import 'package:path_provider/path_provider.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:share_plus/share_plus.dart';

/// Builds a clean, professional prescription-summary PDF and exposes
/// share / print / save-as-PDF actions used on the scan-result screen.
///
/// Required packages (add to pubspec.yaml if missing):
///   share_plus: ^10.0.0
///   pdf: ^3.11.0
///   printing: ^5.13.0
///   path_provider: ^2.1.0
class PrescriptionExportService {
  PrescriptionExportService._();
  static final instance = PrescriptionExportService._();

  /// Creates the PDF bytes for [summary]. Optionally embeds the scan photo.
  Future<Uint8List> buildPdf({
    required String summary,
    required int medicineCount,
    DateTime? scannedAt,
    String? imagePath,
  }) async {
    final doc = pw.Document(
      title: 'MediSense Prescription Summary',
      author: 'MediSense',
    );

    pw.MemoryImage? photo;
    if (imagePath != null && imagePath.isNotEmpty) {
      try {
        final bytes = await File(imagePath).readAsBytes();
        photo = pw.MemoryImage(bytes);
      } catch (e) {
        debugPrint('[PrescriptionExport] could not embed photo: $e');
      }
    }

    final date = scannedAt ?? DateTime.now();
    final dateLabel =
        '${_monthNames[date.month]} ${date.day}, ${date.year}';

    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(40, 36, 40, 40),
        header: (context) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Row(
              crossAxisAlignment: pw.CrossAxisAlignment.center,
              children: [
                pw.Container(
                  width: 28,
                  height: 28,
                  decoration: pw.BoxDecoration(
                    color: PdfColor.fromHex('#0C8577'),
                    borderRadius: pw.BorderRadius.circular(6),
                  ),
                  child: pw.Center(
                    child: pw.Text(
                      'Rx',
                      style: pw.TextStyle(
                        color: PdfColors.white,
                        fontSize: 11,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),
                  ),
                ),
                pw.SizedBox(width: 10),
                pw.Expanded(
                  child: pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      pw.Text(
                        'MediSense',
                        style: pw.TextStyle(
                          fontSize: 14,
                          fontWeight: pw.FontWeight.bold,
                          color: PdfColor.fromHex('#0C8577'),
                        ),
                      ),
                      pw.Text(
                        'Prescription Summary',
                        style: pw.TextStyle(
                          fontSize: 10,
                          color: PdfColor.fromHex('#5E7179'),
                        ),
                      ),
                    ],
                  ),
                ),
                pw.Text(
                  dateLabel,
                  style: pw.TextStyle(
                    fontSize: 10,
                    color: PdfColor.fromHex('#5E7179'),
                  ),
                ),
              ],
            ),
            pw.SizedBox(height: 8),
            pw.Divider(color: PdfColor.fromHex('#E1E9E7'), thickness: 1),
            pw.SizedBox(height: 6),
          ],
        ),
        footer: (context) => pw.Column(
          children: [
            pw.Divider(color: PdfColor.fromHex('#E1E9E7'), thickness: 0.8),
            pw.SizedBox(height: 6),
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text(
                  'Generated by MediSense · For reference only',
                  style: pw.TextStyle(
                    fontSize: 8,
                    color: PdfColor.fromHex('#5E7179'),
                  ),
                ),
                pw.Text(
                  'Page ${context.pageNumber} of ${context.pagesCount}',
                  style: pw.TextStyle(
                    fontSize: 8,
                    color: PdfColor.fromHex('#5E7179'),
                  ),
                ),
              ],
            ),
          ],
        ),
        build: (context) => [
          pw.Text(
            '$medicineCount ${medicineCount == 1 ? 'medicine' : 'medicines'} identified',
            style: pw.TextStyle(
              fontSize: 11,
              color: PdfColor.fromHex('#085F55'),
              fontWeight: pw.FontWeight.bold,
            ),
          ),
          pw.SizedBox(height: 14),
          if (photo != null) ...[
            pw.ClipRRect(
              horizontalRadius: 8,
              verticalRadius: 8,
              child: pw.Image(photo, height: 160, fit: pw.BoxFit.cover),
            ),
            pw.SizedBox(height: 16),
          ],
          pw.Container(
            width: double.infinity,
            padding: const pw.EdgeInsets.all(14),
            decoration: pw.BoxDecoration(
              color: PdfColor.fromHex('#F6F9F8'),
              borderRadius: pw.BorderRadius.circular(8),
              border: pw.Border.all(
                color: PdfColor.fromHex('#DFF2EF'),
                width: 1,
              ),
            ),
            child: pw.Text(
              summary,
              style: pw.TextStyle(
                fontSize: 10.5,
                height: 1.55,
                color: PdfColor.fromHex('#32454E'),
                font: pw.Font.courier(),
              ),
            ),
          ),
          pw.SizedBox(height: 18),
          pw.Container(
            width: double.infinity,
            padding: const pw.EdgeInsets.all(10),
            decoration: pw.BoxDecoration(
              color: PdfColor.fromHex('#FAF0DE'),
              borderRadius: pw.BorderRadius.circular(6),
            ),
            child: pw.Text(
              'Disclaimer: This summary is generated from a scanned image '
                  'and may contain reading errors. Always confirm with your '
                  'prescribing doctor or pharmacist before relying on it.',
              style: pw.TextStyle(
                fontSize: 8.5,
                height: 1.4,
                color: PdfColor.fromHex('#C07A12'),
              ),
            ),
          ),
        ],
      ),
    );

    return doc.save();
  }

  /// Opens the system print / PDF-preview sheet.
  Future<void> printPdf({
    required String summary,
    required int medicineCount,
    DateTime? scannedAt,
    String? imagePath,
  }) async {
    final bytes = await buildPdf(
      summary: summary,
      medicineCount: medicineCount,
      scannedAt: scannedAt,
      imagePath: imagePath,
    );
    await Printing.layoutPdf(
      onLayout: (_) async => bytes,
      name: 'MediSense_Prescription_${_fileStamp()}.pdf',
    );
  }

  /// Shares the PDF via the system share sheet (WhatsApp, email, Drive…).
  Future<void> sharePdf({
    required String summary,
    required int medicineCount,
    DateTime? scannedAt,
    String? imagePath,
  }) async {
    final bytes = await buildPdf(
      summary: summary,
      medicineCount: medicineCount,
      scannedAt: scannedAt,
      imagePath: imagePath,
    );

    final dir = await getTemporaryDirectory();
    final file = File(
      '${dir.path}/MediSense_Prescription_${_fileStamp()}.pdf',
    );
    await file.writeAsBytes(bytes, flush: true);

    await Share.shareXFiles(
      [XFile(file.path, mimeType: 'application/pdf')],
      subject: 'MediSense Prescription Summary',
      text: 'Prescription summary from MediSense',
    );
  }

  /// Shares plain summary text + optional photo (quick WhatsApp path).
  Future<void> shareTextAndPhoto({
    required String summary,
    String? imagePath,
  }) async {
    final files = <XFile>[];
    if (imagePath != null &&
        imagePath.isNotEmpty &&
        await File(imagePath).exists()) {
      files.add(XFile(imagePath));
    }

    if (files.isNotEmpty) {
      await Share.shareXFiles(
        files,
        text: summary,
        subject: 'MediSense Prescription Summary',
      );
    } else {
      await Share.share(
        summary,
        subject: 'MediSense Prescription Summary',
      );
    }
  }

  String _fileStamp() {
    final n = DateTime.now();
    return '${n.year}${n.month.toString().padLeft(2, '0')}'
        '${n.day.toString().padLeft(2, '0')}_'
        '${n.hour.toString().padLeft(2, '0')}'
        '${n.minute.toString().padLeft(2, '0')}';
  }

  static const _monthNames = [
    '',
    'Jan',
    'Feb',
    'Mar',
    'Apr',
    'May',
    'Jun',
    'Jul',
    'Aug',
    'Sep',
    'Oct',
    'Nov',
    'Dec',
  ];
}